// Generates api/fact-presets.ts, the named quest-fact lists world.facts offers, from the Story Engine's research data:
//   main_story    every fact in research/story-engine/main-story-facts.json (the 2.31 main-story table), with its category
//   final_boards  the facts the game's own final boards read, from knowledge/main-story-state.md (the paragraph that begins
//                 "The final boards phase reads")
//
//   bun tools/gen-fact-presets.ts           writes tools/api/fact-presets.ts
//   bun tools/gen-fact-presets.ts --check   exits 1 when the file differs (tools/test/senses.test.ts runs the same check)

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const projectDir = resolve(import.meta.dir, "..");
const repoDir = resolve(projectDir, "..", "..");
export const FACTS_JSON = join(repoDir, "research", "story-engine", "main-story-facts.json");
export const STATE_PAGE = join(repoDir, "knowledge", "main-story-state.md");
export const PRESETS_OUT = join(projectDir, "tools", "api", "fact-presets.ts");

export function mainStory(): { name: string; category: string }[] {
  const data = JSON.parse(readFileSync(FACTS_JSON, "utf8")) as { facts: { name: string; category: string }[] };
  return data.facts.map((f) => ({ name: f.name, category: f.category }));
}

export function finalBoards(): string[] {
  const page = readFileSync(STATE_PAGE, "utf8").replace(/\r\n/g, "\n");
  const start = page.indexOf("The final boards phase reads");
  if (start < 0) throw new Error("knowledge/main-story-state.md no longer has the paragraph 'The final boards phase reads'");
  // Only the list itself: the paragraph goes on to say what the list is for and how the bridge reads it.
  const end = page.indexOf("That list is", start);
  const paragraph = page.slice(start, end > start ? end : page.indexOf("\n", start));
  const names = [...paragraph.matchAll(/`([a-z0-9_]+)`/g)].map((m) => m[1]!);
  return [...new Set(names)];
}

export function render(): string {
  const story = mainStory();
  const boards = finalBoards();
  const lines = [
    "// GENERATED by tools/gen-fact-presets.ts from research/story-engine/main-story-facts.json and knowledge/main-story-state.md.",
    "// Do not edit by hand: run `bun tools/gen-fact-presets.ts` in projects/xf-runtime-bridge (tools/test/senses.test.ts fails when stale).",
    "",
    "/** The 2.31 main-story facts (research/story-engine/main-story-facts.json), each with its category. */",
    "export const MAIN_STORY_FACTS: readonly { readonly name: string; readonly category: string }[] = [",
    ...story.map((f) => `  { name: ${JSON.stringify(f.name)}, category: ${JSON.stringify(f.category)} },`),
    "];",
    "",
    "/** The facts the game's final boards read (knowledge/main-story-state.md): whose fate matters for the ending. */",
    "export const FINAL_BOARDS_FACTS: readonly string[] = [",
    ...boards.map((n) => `  ${JSON.stringify(n)},`),
    "];",
    "",
  ];
  return lines.join("\n");
}

if (import.meta.main) {
  const text = render();
  if (process.argv.includes("--check")) {
    const current = (() => {
      try {
        return readFileSync(PRESETS_OUT, "utf8").replace(/\r\n/g, "\n");
      } catch {
        return "";
      }
    })();
    if (current !== text) {
      console.error("tools/api/fact-presets.ts is out of date. Run: bun tools/gen-fact-presets.ts (in projects/xf-runtime-bridge)");
      process.exit(1);
    }
    console.log("fact presets are current");
  } else {
    writeFileSync(PRESETS_OUT, text);
    console.log(`wrote ${PRESETS_OUT} (${mainStory().length} main-story facts, ${finalBoards().length} final-boards facts)`);
  }
}
