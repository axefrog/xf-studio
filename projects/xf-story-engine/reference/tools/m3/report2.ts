// The M3 run 2 results report: the hook runs by proactivity setting, what ranking chose (E against A1), the automatic critic's tells by arm
// (names masked from the wide registry, so a name never hides a repeated frame), the blind pass by criterion and by rater, and run 1 beside it.
// Usage: bun tools/m3/report2.ts <run2 rundir> <run2 packetdir> <run2 answersdir|-> <run1 packetdir> <run1 answersdir> <out.md>
// Run 1's packet and answers are read, never written. The forced choices carry no significance test: the raters judge the same items.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { type Arm, type Hook, type Packet, type RaterAnswer, ARM_NAMES, CRITERIA, score } from '../../src/m3/blind.ts';
import { findings, tells } from '../../src/m3/critic.ts';
import type { RunRecord } from '../../src/m3/transcript.ts';
import { OFFER_PACK } from '../../src/m3/kits.ts';
import { allNames, peopleIn } from '../../src/sim/names.ts';

const [runs, packetDir, answersDir, run1Packet, run1Answers, out] = process.argv.slice(2);
if (!runs || !packetDir || !answersDir || !run1Packet || !run1Answers || !out) throw new Error('usage: report2 <rundir> <packetdir> <answersdir|-> <run1 packetdir> <run1 answersdir> <out.md>');

const lines: string[] = ['# M3 run 2 results (generated by tools/m3/report2.ts)', ''];
const pct = (x: number): string => `${Math.round(x * 100)} %`;

// ---- the hook runs ----
const recs = readdirSync(runs).filter((f) => f.endsWith('.json')).sort().map((f) => ({ f: f.replace('.json', ''), r: JSON.parse(readFileSync(`${runs}/${f}`, 'utf8')) as RunRecord }));
const isOffer = (d: RunRecord['deliveries'][number]): boolean => d.what === 'offer' && d.template.startsWith(OFFER_PACK);
lines.push('## Hooks by run and proactivity setting', '', '| Run | Arm | Tempo | State | Game days | Hooks sown | with an ask | texture | R2 offers |', '|---|---|---|---|---|---|---|---|---|');
const byArm: Record<string, { sown: number; offers: number; runs: number }> = {};
// a hook is one decision of the sower; an offer that is shown has three deliveries (the ask, the outcome of V's answer, the closing)
for (const { f, r } of recs) {
  const arm = f.startsWith('A1') ? 'A1' : 'E';
  const decisions = r.decisions.filter((d) => d.rule === 'sow');
  const offers = decisions.filter((d) => String(d.data.kit).startsWith(OFFER_PACK)).length;
  const shown = r.deliveries.filter(isOffer).length;
  const a = (byArm[arm] ??= { sown: 0, offers: 0, runs: 0 });
  a.sown += decisions.length; a.offers += offers; a.runs++;
  lines.push(`| ${f} | ${arm} | ${r.tempo} | ${r.state} | ${(r.windows / 144).toFixed(1)} | ${decisions.length} | ${offers} (${shown} asks shown) | ${decisions.length - offers} | ${r.deliveries.filter((d) => d.layer === 'authored' && d.what === 'offer').length} |`);
}
lines.push('');

// ---- what ranking chose: the features of the candidates each arm sowed ----
lines.push('## What ranking chose (E against A1, over every hook the runs sowed)', '', 'The means are over every hook sown, and then over the offers alone. F3 is stakes (distinct harmful effects), F5 the personal link (V took part, 2, plus the people V was shown), F11 timeliness (1 is just now). A hook is one decision of the sower.', '', '| Arm | Runs | Hooks sown | with an ask | share with an ask | mean F3 | mean F5 | mean F11 | offers: mean F3 | offers: mean F5 | offers: mean F11 | offers by kit |', '|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const arm of ['E', 'A1']) {
  const rs = recs.filter((x) => (x.f.startsWith('A1') ? 'A1' : 'E') === arm);
  const dec = rs.flatMap((x) => x.r.decisions.filter((d) => d.rule === 'sow'));
  const isOfferKit = (d: (typeof dec)[number]): boolean => String(d.data.kit).startsWith(OFFER_PACK);
  const mean = (k: string, only?: (d: (typeof dec)[number]) => boolean): string => {
    const xs = dec.filter((d) => (only ? only(d) : true)).map((d) => d.data.features?.[k]).filter((v): v is number => typeof v === 'number');
    return xs.length ? (xs.reduce((a, b) => a + b, 0) / xs.length).toFixed(2) : 'n/a';
  };
  const kits: Record<string, number> = {};
  for (const d of dec) if (String(d.data.kit).startsWith(OFFER_PACK)) kits[String(d.data.kit).split(':')[1]!] = (kits[String(d.data.kit).split(':')[1]!] ?? 0) + 1;
  const a = byArm[arm] ?? { sown: 0, offers: 0, runs: 0 };
  lines.push(`| ${arm} | ${a.runs} | ${a.sown} | ${a.offers} | ${a.sown ? pct(a.offers / a.sown) : 'n/a'} | ${mean('F3')} | ${mean('F5')} | ${mean('F11')} | ${mean('F3', isOfferKit)} | ${mean('F5', isOfferKit)} | ${mean('F11', isOfferKit)} | ${Object.entries(kits).map(([k, v]) => `${k} ${v}`).join(', ')} |`);
}
lines.push('');

// ---- the automatic critic (run 2 packet) ----
const readPacket = (dir: string) => {
  const packet = JSON.parse(readFileSync(`${dir}/packet.json`, 'utf8')) as Pick<Packet, 'cards' | 'orders' | 'pairs'>;
  const key = JSON.parse(readFileSync(`${dir}/key.json`, 'utf8')) as { key: Packet['key']; pairKey: Packet['pairKey']; n: number; available: Record<string, number> };
  return { packet, key };
};
const p2 = readPacket(packetDir);
const registry = allNames();
// the strings that mask names (every token of the registry, and any pair of capitalised words) are not the people a card names (a given and a family name are one person)
const namesOf = (h: Hook): string[] => [...(h.text.match(/\b[A-Z][a-z]+ [A-Z][a-z]+\b/g) ?? []).filter((x) => !['Tyger Claws', 'Night City'].includes(x)), ...registry.filter((n) => new RegExp(`\\b${n}\\b`).test(h.text))];
const hooks2: Hook[] = p2.packet.cards.map((c) => ({ arm: p2.key.key[c.id]!.arm, text: c.text, meta: {} }));
const t2 = tells(hooks2, namesOf, (h) => peopleIn(h.text));
lines.push(`## What would give a card away (automatic critic), ${p2.key.n} cards per arm`, '', 'Names are masked from the whole name registry, not only from the pattern of two capitalised words.', '', '| Arm | Repeated skeleton | Most on one skeleton | Word-pair diversity | Cause or order word | Mean words | Priced | Names two people |', '|---|---|---|---|---|---|---|---|');
for (const [arm, v] of Object.entries(t2)) lines.push(`| ${arm} ${ARM_NAMES[arm as Arm]} | ${v.repeatedSkeleton} | ${v.maxSkeleton} | ${v.bigramDiversity} | ${v.causeMarker} | ${v.meanWords} | ${v.priced} | ${v.twoPeople} |`);
lines.push('', ...findings(t2).map((f) => `- ${f}`), '');
const e2 = t2.E;
if (e2) lines.push(`**Skeleton sharing for the engine (E): ${pct(e2.repeatedSkeleton)} of its cards share a masked skeleton with another (run 1: 75 %); the target was under 30 %.** The most on one skeleton is ${e2.maxSkeleton}.`, '');
lines.push(`Hooks with an ask available before sampling: ${JSON.stringify(p2.key.available)}.`, '');

// ---- the blind pass, run 2 and run 1 ----
function loadAnswers(dir: string): RaterAnswer[] {
  if (dir === '-' || !existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')) as RaterAnswer);
}
const a2 = loadAnswers(answersDir);
const p1 = readPacket(run1Packet);
const a1 = loadAnswers(run1Answers);
const full = (p: ReturnType<typeof readPacket>): Packet => ({ ...p.packet, key: p.key.key, pairKey: p.key.pairKey });
const s2 = a2.length ? score(full(p2), a2) : undefined;
const s1 = a1.length ? score(full(p1), a1) : undefined;

if (s2 && s1) {
  lines.push(`## Blind pass: run 2, ${a2.length} raters (${s2.raters.join(', ')}), against run 1 (${a1.length} raters)`, '', 'Means on a scale of 1 to 7 over each rater\'s ratings of the arm; run 1 in brackets. E is the engine, A1 random within gates, A3 the Radiant-style baseline, A4 the authored seed. In run 2 the engine and A1 cards are hooks with an ask.', '', '| Arm | Cards rated | ' + CRITERIA.map((c) => c.id).join(' | ') + ' | Called "program" |', '|---|---|' + CRITERIA.map(() => '---').join('|') + '|---|');
  for (const arm of ['E', 'A1', 'A3', 'A4']) {
    const v = s2.arms[arm], w = s1.arms[arm];
    if (!v) continue;
    lines.push(`| ${arm} ${ARM_NAMES[arm as Arm]} | ${v.n} | ${CRITERIA.map((c) => `${v.mean[c.id]} (${w?.mean[c.id] ?? 'n/a'})`).join(' | ')} | ${v.detected}/${v.detectedOf} (${w ? `${w.detected}/${w.detectedOf}` : 'n/a'}) |`);
  }
  lines.push('');
  const order = (a: { x: string; y: string; criterion: string }, b: { x: string; y: string; criterion: string }): number => (a.x + a.y + a.criterion < b.x + b.y + b.criterion ? -1 : 1);
  const raters2 = s2.perRater.map((r) => r.rater);
  lines.push('Forced choices, per rater: wins of the first arm of the row, of the rater\'s own count. Run 1\'s per-rater counts follow the run 2 ones in each cell, in the order of that run\'s raters (' + s1.raters.join(', ') + ').', '', `| First | Second | Question | ${raters2.join(' | ')} | run 1 |`, `|---|---|---|${raters2.map(() => '---').join('|')}|---|`);
  for (const x of s2.pairs.slice().sort(order)) {
    const cell = (r: { pairs: typeof s2.pairs }): string => { const o = r.pairs.find((q) => q.x === x.x && q.y === x.y && q.criterion === x.criterion); return o ? `${o.wins} of ${o.n}` : 'n/a'; };
    const prev = s1.perRater.map((r) => cell(r).replace(' of ', '/')).join(', ');
    lines.push(`| ${x.x} | ${x.y} | ${x.criterion} | ${s2.perRater.map(cell).join(' | ')} | ${prev} |`);
  }
  lines.push('');
  lines.push(`Disagreement (share of rater pairs differing by 2 or more points): ${JSON.stringify(s2.disagreement)} (run 1: ${JSON.stringify(s1.disagreement)}).`, '');

  // the decision rule of the scoring sheet, rater by rater
  const wins = (arm1: Arm, arm2: Arm, crit: 'follow' | 'caused'): number[] => s2.perRater.map((r) => {
    const [x, y] = [arm1, arm2].sort() as [Arm, Arm];
    const o = r.pairs.find((q) => q.x === x && q.y === y && q.criterion === crit);
    if (!o) return NaN;
    return arm1 === x ? o.wins / o.n : 1 - o.wins / o.n;
  });
  const row = (a: Arm, b: Arm): string => `${a} against ${b}: follow ${wins(a, b, 'follow').map((v) => pct(v)).join(', ')}; caused ${wins(a, b, 'caused').map((v) => pct(v)).join(', ')}`;
  lines.push('### The decision rule, rater by rater (share of forced choices won, in the order ' + raters2.join(', ') + ')', '', `- ${row('E', 'A3')}`, `- ${row('E', 'A1')}`, `- ${row('A4', 'A3')}`, '',
    `Engine beats the baseline by the rule of the scoring sheet when its share against A3 is above one half on both questions in every rater alone, and its means on "caused" and "pull" are above A3's. Means: E caused ${s2.arms.E?.mean.caused}, pull ${s2.arms.E?.mean.pull}; A3 caused ${s2.arms.A3?.mean.caused}, pull ${s2.arms.A3?.mean.pull}.`, '');
  for (const x of a2) if (x.critic) lines.push(`### Critic, ${x.rater}`, '', x.critic, '');
} else if (s1) {
  lines.push('## Blind pass: run 2 has no answers yet.', '');
}

// ---- how the packet was built ----
const inputsFile = `${packetDir}/inputs.json`;
if (existsSync(inputsFile)) {
  const m = JSON.parse(readFileSync(inputsFile, 'utf8')) as { a3Rule: string; runs: Array<{ file: string; hash: string }>; n: number; raters: number; names?: string; tier?: string };
  lines.push('## How the packet was built', '', `The packet is rebuilt byte for byte from blind/inputs.json: ${m.runs.length} hook runs by file name and record hash (${m.runs.map((r) => r.file.replace('.json', '')).join(', ')}), ${m.n} hooks per arm (engine and A1 cards are the hooks with an ask: tier "${m.tier ?? 'all'}"), ${m.raters} raters, A3 under the \`${m.a3Rule}\` slot rule, the wide name registry for every arm (names "${m.names ?? 'legacy'}").`, '');
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
