// The M3 results report: the proactivity table from the hook runs, the automatic critic's tells by arm, and (when there are
// answers) the blind scorer's results by criterion.
// Usage: bun tools/m3/report.ts <rundir> <packetdir> <answersdir|-> <out.md>

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { type Arm, type Hook, type Packet, type RaterAnswer, ARM_NAMES, CRITERIA, score } from '../../src/m3/blind.ts';
import { findings, tells } from '../../src/m3/critic.ts';
import type { RunRecord } from '../../src/m3/transcript.ts';

const [runs, packetDir, answersDir, out] = process.argv.slice(2);
if (!runs || !packetDir || !answersDir || !out) throw new Error('usage: report <rundir> <packetdir> <answersdir|-> <out.md>');

const lines: string[] = ['# M3 results (generated by tools/m3/report.ts)', ''];

// ---- proactivity ----
const recs = readdirSync(runs).filter((f) => f.endsWith('.json')).map((f) => ({ f: f.replace('.json', ''), r: JSON.parse(readFileSync(`${runs}/${f}`, 'utf8')) as RunRecord }));
lines.push('## Hooks by run and proactivity setting', '', '| Run | Arm | Tempo | State | Game days | Hooks sown and shown | R2 offers | Decisions logged |', '|---|---|---|---|---|---|---|---|');
for (const { f, r } of recs) {
  const hooks = r.deliveries.filter((d) => d.layer !== 'authored').length;
  const offers = r.deliveries.filter((d) => d.layer === 'authored' && d.what === 'offer').length;
  lines.push(`| ${f} | ${f.startsWith('A1') ? 'A1' : 'E'} | ${r.tempo} | ${r.state} | ${(r.windows / 144).toFixed(1)} | ${hooks} | ${offers} | ${r.decisions.length} |`);
}
lines.push('');

// ---- critic ----
const packet = JSON.parse(readFileSync(`${packetDir}/packet.json`, 'utf8')) as Pick<Packet, 'cards' | 'orders' | 'pairs'>;
const keyFile = JSON.parse(readFileSync(`${packetDir}/key.json`, 'utf8')) as { key: Packet['key']; pairKey: Packet['pairKey']; n: number; available: Record<string, number> };
const hooks: Hook[] = packet.cards.map((c) => ({ arm: keyFile.key[c.id]!.arm, text: c.text, meta: {} }));
const namesOf = (h: Hook): string[] => (h.text.match(/\b[A-Z][a-z]+ [A-Z][a-z]+\b/g) ?? []).filter((x) => !['Tyger Claws', 'Night City'].includes(x));
const t = tells(hooks, namesOf);
lines.push(`## What would give a card away (automatic critic), ${keyFile.n} cards per arm`, '', '| Arm | Repeated skeleton | Most on one skeleton | Word-pair diversity | Cause or order word | Mean words | Priced | Names two people |', '|---|---|---|---|---|---|---|---|');
for (const [arm, v] of Object.entries(t)) lines.push(`| ${arm} ${ARM_NAMES[arm as Arm]} | ${v.repeatedSkeleton} | ${v.maxSkeleton} | ${v.bigramDiversity} | ${v.causeMarker} | ${v.meanWords} | ${v.priced} | ${v.twoPeople} |`);
lines.push('', ...findings(t).map((f) => `- ${f}`), '', `Hooks available before sampling: ${JSON.stringify(keyFile.available)}.`, '');

// ---- blind scorer ----
if (answersDir !== '-' && existsSync(answersDir)) {
  const answers = readdirSync(answersDir).filter((f) => f.endsWith('.json')).map((f) => ({ f, a: JSON.parse(readFileSync(`${answersDir}/${f}`, 'utf8')) as RaterAnswer }));
  if (answers.length) {
    const p: Packet = { ...packet, key: keyFile.key, pairKey: keyFile.pairKey };
    const s = score(p, answers.map((x) => x.a));
    lines.push(`## Blind pass: ${answers.length} rater${answers.length === 1 ? '' : 's'} (${s.raters.join(', ')})`, '', '| Arm | Cards rated | ' + CRITERIA.map((c) => c.id).join(' | ') + ' | Called "program" |', '|---|---|' + CRITERIA.map(() => '---').join('|') + '|---|');
    for (const [arm, v] of Object.entries(s.arms)) lines.push(`| ${arm} ${ARM_NAMES[arm as Arm]} | ${v.n} | ${CRITERIA.map((c) => v.mean[c.id]).join(' | ')} | ${v.detected}/${v.detectedOf} |`);
    lines.push('', 'Forced choices (the first arm of the row against the second; wins of the first, sign test two-sided):', '', '| First | Second | Question | Wins | Of | p |', '|---|---|---|---|---|---|');
    for (const x of s.pairs.sort((a, b) => (a.x + a.y + a.criterion < b.x + b.y + b.criterion ? -1 : 1))) lines.push(`| ${x.x} | ${x.y} | ${x.criterion} | ${x.wins} | ${x.n} | ${x.p} |`);
    lines.push('', `Disagreement (share of rater pairs differing by 2 or more points): ${JSON.stringify(s.disagreement)}.`, '');
    for (const x of answers) if (x.a.critic) lines.push(`### Critic, ${x.a.rater}`, '', x.a.critic, '');
  }
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
