const digest = (body: string | Buffer) => createHash("sha256").update(body).digest("hex");
const MOD = EYE_MAKEUP_MOD.modName;
/** A profile of three sections, frameworks at the top of the pane (the last rows of the file: MO2's pane is the file reversed). */
const MODLIST = [
  "# This file was automatically generated by Mod Organizer.",
  "+Neon Lashes",
  "-Old Hair",
  "+Looks_separator",
  "+Better Lighting",
  "+Visuals_separator",
  "+ArchiveXL",
  "+TweakXL",
  "+CORE, LIBS, FRAMEWORKS_separator",
].join("\r\n") + "\r\n";

function fixture(route: "direct" | "mo2", modlist: string | Buffer = MODLIST, options: { receipts?: string; legacy?: string[]; readOnly?: string; ansi?: number | null } = {}) {
  const root = mkdtempSync(join(tmpdir(), "xfs-mod-install-"));
  const game = join(root, "game"), mo2 = join(root, "mo2"), store = join(root, "candidates");
  const receipts = join(root, options.receipts ?? "receipts");
  const profile = "Main (2026)";
  mkdirSync(join(game, "bin", "x64"), { recursive: true });
  mkdirSync(join(game, "archive", "pc"), { recursive: true });
  writeFileSync(join(game, "bin", "x64", "Cyberpunk2077.exe"), "fixture");
  mkdirSync(join(mo2, "mods", "Neon Lashes"), { recursive: true });
  mkdirSync(join(mo2, "profiles", profile), { recursive: true });
  const modlistFile = join(mo2, "profiles", profile, "modlist.txt");
  writeFileSync(modlistFile, modlist);
  mkdirSync(store);
  const settings: LocalSettings = { ...defaultLocalSettings(), revision: 3, gameRoot: game, mo2Root: mo2, mo2ProfileId: profile, launchRoute: route };
  const running: RunningApps = { mo2: false, game: false };
  let frameworks = ["ArchiveXL", "TweakXL"];
  const revealed: string[] = [];
  const make = (receiptsRoot = receipts, legacy = options.legacy?.map(name => join(root, name))) => new ModInstallHost({ candidateStore: store,
    receiptsRoot, legacyReceiptsRoots: legacy, settings: () => settings, running: () => ({ ...running }), frameworkMods: () => frameworks,
    ansiCodePage: () => options.ansi ?? null, readOnly: options.readOnly, reveal: path => { revealed.push(path); return true; } });
  const host = make();
  const target = route === "direct" ? join(game, "archive", "pc", "mod") : join(mo2, "mods", MOD, "archive", "pc", "mod");
  function candidate(id: string, version: string, xl = `${version}-1`, modName?: string) {
    const folder = join(store, id), payload = join(folder, "archive", "pc", "mod");
    mkdirSync(payload, { recursive: true });
    const files = ["xfs_test.archive", "xfs_test.archive.xl"].map((name, index) => {
      const body = index ? xl : `${version}-0`;
      writeFileSync(join(payload, name), body);
      return { path: `archive/pc/mod/${name}`, sha256: digest(body), bytes: Buffer.byteLength(body) };
    });
    writeFileSync(join(folder, "manifest.json"), JSON.stringify(modName
      ? { schema: "xfs/local-package-2", productId: "11111111-2222-4333-8444-555555555555", modName, nameSource: "plan", archive: "xfs_test",
        features: [{ feature: "eye-makeup", namespace: "xfs_test" }], files, verifiedUnpackedFiles: 2, installed: false, gameRenderingVerified: false }
      : { schema: "xfs/local-package-1", namespace: "xfs_test", verifiedUnpackedFiles: 2, installed: false, gameRenderingVerified: false, files }));
  }
  const lines = () => readFileSync(modlistFile, "utf8").split("\r\n");
  return { root, game, mo2, store, receipts, settings, host, make, target, candidate, modlistFile, lines, revealed, running,
    setRunning: (on: boolean) => { running.mo2 = on; }, setFrameworks: (names: string[]) => { frameworks = names; },
    cleanup: () => rmSync(root, { recursive: true, force: true }) };
}
const refusal = async (run: () => Promise<unknown>) => { try { await run(); } catch (error) { return error as ModInstallError; } throw Error("Expected a refusal."); };
/** Every file under `folder`, relative, sorted (to prove nothing was written). */
const tree = (folder: string): string[] => existsSync(folder)
  ? readdirSync(folder, { recursive: true, withFileTypes: true }).filter(entry => entry.isFile()).map(entry => join(entry.parentPath, entry.name).slice(folder.length + 1)).sort()
  : [];

test("MO2: the plan names the mod, its folder and the one mod-list row, then install adds exactly that", async () => {
  const f = fixture("mo2");
  try {
    f.candidate("first", "one");
    const plan = await f.host.plan("first");
    expect(plan).toMatchObject({ route: "mo2", modName: MOD, place: "Mod Organizer 2 (profile “Main (2026)”)", blocked: null, next: null, replacing: false });
    expect(plan.changes[0]).toBe(`Add the mod “${MOD}” to Mod Organizer 2, with its 2 files in ${f.target}.`);
    // The pane shows the file reversed: the new row goes at the bottom of the first section that holds no frameworks ("Looks").
    expect(plan.changes[1]).toBe(`Add “${MOD}” to the profile “Main (2026)”, switched on. At the bottom of the "Looks" section, where Mod Organizer puts newly installed mods.`);
    expect(plan.changes[2]).toBe("Nothing else in your mod list changes.");
    const before = f.lines();
    const result = await f.host.install("first", plan.token);
    expect(result.message).toContain("switched on in the profile “Main (2026)”");
    expect(readdirSync(f.target).sort()).toEqual(["xfs_test.archive", "xfs_test.archive.xl"]);
    // One row added, directly after the comment (the bottom of the "Looks" section in the pane); nothing else moved.
    expect(f.lines()).toEqual([before[0], `+${MOD}`, ...before.slice(1)]);
    expect(readdirSync(join(f.receipts, "modlists"))).toHaveLength(1);
    expect(readdirSync(join(f.mo2, "profiles", "Main (2026)")).sort()).toEqual(["modlist.txt"]);
  } finally { f.cleanup(); }
});

