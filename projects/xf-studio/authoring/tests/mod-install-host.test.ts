/** The journal a real update leaves when it is interrupted after `done` of its two renames (the game holding the old `.archive`). */
function interrupt(f: ReturnType<typeof fixture>, next: string, done: 0 | 1 | 2) {
  const name = readdirSync(f.receipts).find(file => /^[a-f0-9]{24}\.json$/.test(file))!;
  const prior = JSON.parse(readFileSync(join(f.receipts, name), "utf8"));
  const backup = join(f.receipts, `${prior.targetId}-test-backup-${next}`); mkdirSync(backup);
  for (const entry of prior.files) writeFileSync(join(backup, entry.path.split("/").at(-1)), readFileSync(join(f.target, entry.path.split("/").at(-1))));
  const files = JSON.parse(readFileSync(join(f.store, next, "manifest.json"), "utf8")).files as { path: string }[];
  const pending = { ...prior, candidateId: next, files, installedAt: new Date().toISOString(), rollback: { prior: { ...prior, rollback: null }, backup } };
  writeFileSync(join(f.receipts, `${prior.targetId}.journal.json`), JSON.stringify({ schema: "xfs/install-journal-1", targetId: prior.targetId,
    target: prior.target, names: files.map(x => x.path.split("/").at(-1)), next: files, prior, backup, pending }));
  for (const entry of files.slice(0, done)) writeFileSync(join(f.target, entry.path.split("/").at(-1)!), readFileSync(join(f.store, next, ...entry.path.split("/"))));
}

test("an interrupted install is finished or undone on the next plan, once the game is closed (INSTALL-02)", async () => {
  const f = fixture("direct");
  try {
    f.candidate("first", "one"); f.candidate("second", "two");
    await f.host.install("first", (await f.host.plan("first")).token);
    interrupt(f, "second", 1);
    // The game still holds the file: nothing is touched, and the plan says to close it.
    f.running.game = true;
    const waiting = await f.host.plan("second");
    expect(waiting).toMatchObject({ next: "retry", blocked: `Cyberpunk 2077 is running, and an earlier install of “${MOD}” needs finishing. Close the game, then choose Check again.` });
    expect(readdirSync(f.receipts).some(name => name.endsWith(".journal.json"))).toBe(true);
    f.running.game = false;
    const plan = await f.host.plan("second");
    expect(plan.notes[0]).toBe(`An earlier install of “${MOD}” was interrupted; XF Studio has put back the copy from before it.`);
    expect(plan).toMatchObject({ blocked: null, replacing: true });
    expect(readFileSync(join(f.target, "xfs_test.archive"), "utf8")).toBe("one-0");
    await f.host.install("second", plan.token);
    expect(readFileSync(join(f.target, "xfs_test.archive"), "utf8")).toBe("two-0");
    // All new files already in place: the install is finished instead.
    f.candidate("third", "three");
    interrupt(f, "third", 2);
    expect((await f.host.plan("third")).notes[0]).toBe(`An earlier install of “${MOD}” was interrupted; XF Studio has finished it.`);
    expect(readFileSync(join(f.target, "xfs_test.archive"), "utf8")).toBe("three-0");
  } finally { f.cleanup(); }
});

