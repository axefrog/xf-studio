// "Add to my mod manager" (UI-82) over a fake MO2 tree and game folder: the plan names exactly what changes and where, the one
// mod-list row lands in the right separator section (the file is the reverse of MO2's pane), consent is to that plan only, and
// every refusal (a folder or files XF Studio didn't make, MO2 or the game open, a changed list, a duplicate elsewhere) changes
// nothing. The install review's fixes are pinned here too (INSTALL-01..11, UI-99..100).
