/**
 * Generates `research/authoring/ui-action-catalogue.md` from the action registry (`src/compose/studio-registry.ts`): every
 * registered owner's actions, gesture proposals and asynchronous requests with their scope, effect, Undo policy and inputs.
 * The registry is the single source of truth; never edit the Markdown by hand. `bun tools/action-catalogue.ts` (in
 * `projects/xf-studio/authoring`) rewrites it, and `tests/action-catalogue.test.ts` fails when it is stale.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { STUDIO_OWNERS } from "../src/compose/studio-registry";
import type { PayloadSchema, UndoPolicy } from "../src/platform/api";

export const CATALOGUE_PATH = fileURLToPath(new URL("../../../../research/authoring/ui-action-catalogue.md", import.meta.url));

type Row = { kind: string; scope: readonly string[]; effect: string; undo?: UndoPolicy; payload?: PayloadSchema;
  variants?: Record<string, { payload: PayloadSchema; undo: UndoPolicy }>; cancellable?: boolean };

const cell = (text: string) => text.replace(/\|/g, "\\|");
const inputs = (payload: PayloadSchema = {}) =>
  Object.entries(payload).map(([name, value]) => `${name}${value.required ? "" : "?"}: ${value.type}`).join(", ");
const variants = (row: Row) => Object.entries(row.variants ?? {})
  .map(([name, variant]) => `${name}${variant.undo !== row.undo ? ` (${variant.undo})` : ""}`).join(", ");

function table(rows: readonly Row[], async: boolean): string[] {
  const head = async ? ["| Request | Scope | Effect | Cancellable | Inputs |", "|---|---|---|---|---|"]
    : ["| Action | Scope | Effect | Undo | Inputs | Variants |", "|---|---|---|---|---|---|"];
  return [...head, ...rows.map(row => async
    ? `| \`${row.kind}\` | ${row.scope.join(", ")} | ${row.effect} | ${row.cancellable ? "yes" : "no"} | ${cell(inputs(row.payload))} |`
    : `| \`${row.kind}\` | ${row.scope.join(", ")} | ${row.effect} | ${row.undo} | ${cell(inputs(row.payload))} | ${cell(variants(row))} |`)];
}

/** The catalogue's Markdown, from the owners as registered (registration order is catalogue order). */
export function renderCatalogue(): string {
  let actions = 0, requests = 0, gestures = 0;
  const sections = STUDIO_OWNERS.flatMap(owner => {
    const async = "async" in owner && owner.async === true;
    const rows: Row[] = Object.entries(owner.actions as unknown as Record<string, { descriptor: Omit<Row, "kind"> }>)
      .map(([kind, spec]) => ({ ...spec.descriptor, kind }));
    const kind = owner.owner === "feature" ? "feature module" : async ? "system family, asynchronous requests" : "system family";
    const lines = ["", `## ${owner.label} (\`${owner.id}\`, ${kind})`, "", ...table(rows, async)];
    if (async) requests += rows.length; else actions += rows.length;
    const proposals = owner.owner === "feature" ? owner.gestures?.descriptors : undefined;
    if (proposals && Object.keys(proposals).length) {
      const gestureRows = Object.entries(proposals).map(([kind, descriptor]) => ({ ...descriptor, kind }));
      gestures += gestureRows.length;
      lines.push("", "Gesture proposals (sent inside a gesture session; the session owns the Undo step):", "", ...table(gestureRows, false));
    }
    return lines;
  });
  return [
    "# XF Studio action catalogue",
    "",
    "Generated by `bun tools/action-catalogue.ts` (in `projects/xf-studio/authoring`) from the action registry " +
      "(`src/compose/studio-registry.ts`); don't edit it by hand. `tests/action-catalogue.test.ts` fails when it is stale.",
    "",
    "Every user-visible action is registered by exactly one owner, a system family or a feature module, in the order below. " +
      "An action's qualified ID is `<owner>/<kind>`. **Scope** is what it targets, **Effect** what it changes, **Undo** the history it " +
      "records into (`none` records nothing), **Inputs** its payload fields (`?` marks an optional one) and **Variants** its named " +
      "commands, with their Undo policy where it differs. Capabilities, limits and history labels are answered at run time by the " +
      "registry (`capability`, `limitsFor`, `choicesFor`). Modules whose actions route through their own service instead are recorded " +
      "exceptions in the [UI architecture boundary](ui-architecture-boundary.md).",
    "",
    `${actions} actions, ${gestures} gesture proposals and ${requests} asynchronous requests from ${STUDIO_OWNERS.length} owners.`,
    ...sections,
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(CATALOGUE_PATH, renderCatalogue());
  console.log(`Wrote ${CATALOGUE_PATH}.`);
}
